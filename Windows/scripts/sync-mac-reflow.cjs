// Regenerate the platform-neutral reader from the verified macOS template.
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(process.argv[2] || path.resolve(__dirname, '../../Sources/ReadingCompanion/ReflowReaderHTML.swift'), 'utf8');
let html = source.split('private static let template = #"""')[1].split('"""#')[0].trim().split('\n').map(line => line.replace(/^    /, '')).join('\n');
html = html.replace('window.webkit.messageHandlers.readerSelection.postMessage(payload)', "window.parent.postMessage({type:'reader:selection',...payload},'*')");
html = html.replace('window.webkit.messageHandlers.readerNavigation.postMessage({', "window.parent.postMessage({type:'reader:navigation',").replace('position:readingPosition()});', "position:readingPosition()},'*');");
html = html.replace('readerConfigure=(scale,count,saved,location)=>', 'readerConfigure=(scale,count,saved,location,legacyPage)=>').replace('currentPage=pageForLocation(location||0)', 'currentPage=Number.isInteger(legacyPage)?legacyPage:pageForLocation(location||0)');
html = html.replace('window.webkit.messageHandlers.readerMark.postMessage({id:hit.id,x:hit.left,y:hit.top,width:hit.width,height:hit.height})', "window.parent.postMessage({type:'reader:mark',id:hit.id,x:hit.left,y:hit.top,width:hit.width,height:hit.height},'*')");
const bridge = `
window.addEventListener('message',event=>{
  if(event.source!==window.parent)return;
  const d=event.data||{};
  switch(d.type){
    case 'reader:configure':window.readerConfigure(d.scale,d.count,d.position,d.location,d.legacyPage);break;
    case 'reader:setScale':window.readerSetScale(d.value);break;
    case 'reader:setSpreadCount':window.readerSetSpreadCount(d.count);break;
    case 'reader:turn':window.readerTurn(d.direction);break;
    case 'reader:goToLocation':window.readerGoToLocation(d.location);break;
    case 'reader:goToAnchor':window.readerGoToAnchor(d.anchor);break;
    case 'reader:goToPage':currentPage=Math.max(0,Number(d.page)||0);position(false);renderMarks();report();break;
    case 'reader:textForPageRange':window.parent.postMessage({type:'reader:textForPageRangeResult',id:d.id,result:window.readerTextForPageRange(d.start,d.end)},'*');break;
    case 'reader:resolveReferences':window.parent.postMessage({type:'reader:textForPageRangeResult',id:d.id,result:window.readerResolveReferences(d.references)},'*');break;
    case 'reader:applyMarks':window.readerApplyMarks(d.marks);break;
    case 'reader:applyCharacters':window.readerApplyCharacters(d.characters);break;
    case 'reader:find':window.readerFind(d.query);break;
    case 'reader:goToSearch':window.readerGoToSearch(d.query,d.sectionID,d.ratio,d.snippet,d.fallbackLocation);break;
    case 'reader:clearSelection':window.readerClearSelection();break;
  }
});
window.parent.postMessage({type:'reader:ready'},'*');
`;
html = html.replace('  layout(false);\n})();', '  layout(false);\n' + bridge + '\n})();');
if (!html.includes("type:'reader:ready'")) throw new Error('macOS template layout boundary changed');
const generated = '// Generated by scripts/sync-mac-reflow.cjs from macOS 0.55.6. Do not hand edit.\nexport const TEMPLATE = [\n' + html.split('\n').map(line => '  ' + JSON.stringify(line)).join(',\n') + '\n].join("\\n");\n';
fs.writeFileSync(path.resolve(__dirname, '../src/renderer/reflow-template.mjs'), generated);
